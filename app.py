                    if st.button("🗑️ 선택한 인원 삭제", key="btn_del_master"):
                        if not confirm_master_del:
                            st.warning("삭제 확인에 체크해 주세요.")
                        else:
                            master_deleted = False
                            try:
                                delete_master_member(del_master_target)
                                master_deleted = True
                            except Exception as e:
                                st.error(f"인원을 삭제하지 못했습니다: {e}")
                            if master_deleted:
                                st.success(f"'{del_master_target}'님을 전체 인원에서 삭제했습니다.")
                                st.rerun()
