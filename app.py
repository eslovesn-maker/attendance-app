def _exact_match(a: str, b: str) -> bool:
    return hmac.compare_digest(str(a).encode("utf-8"), str(b).encode("utf-8"))


def _auth_key(password: str) -> bytes:
    salt = str(st.secrets.get("APP_AUTH_SALT", "")).strip()
    return f"{salt}::{password}".encode("utf-8")


def _sign(username: str, password: str, expires_at: int) -> str:
    msg = f"{username}|{expires_at}".encode("utf-8")
    return hmac.new(_auth_key(password), msg, hashlib.sha256).hexdigest()


def _make_auth_token(username: str, password: str) -> str:
    expires_at = int(time.time()) + AUTH_DAYS * 86400
    return f"{expires_at}.{_sign(username, password, expires_at)}"


def _verify_auth_token(token: str, username: str, password: str) -> bool:
    try:
        exp_str, signature = str(token).split(".", 1)
        expires_at = int(exp_str)
    except (ValueError, AttributeError):
        return False
    if expires_at < int(time.time()):
        return False
    return hmac.compare_digest(signature, _sign(username, password, expires_at))


def _read_auth_cookie() -> str:
    try:
        return str(st.context.cookies.get(AUTH_COOKIE, "") or "")
    except Exception:
        return ""


def _inject_cookie_script(value: str, max_age: int) -> None:
    safe_value = json.dumps(value)
    components.html(
        f"""
        <script>
        try {{
            var secure = window.parent.location.protocol === 'https:' ? '; Secure' : '';
            window.parent.document.cookie = "{AUTH_COOKIE}=" + {safe_value}
                + "; path=/; max-age={max_age}; SameSite=Lax" + secure;
        }} catch (e) {{}}
        </script>
        """,
        height=0,
    )


def flush_cookie_actions() -> None:
    token = st.session_state.pop("_cookie_set", None)
    if token:
        _inject_cookie_script(str(token), AUTH_DAYS * 86400)
    if st.session_state.pop("_cookie_clear", False):
        _inject_cookie_script("", 0)


def render_login_screen() -> None:
    flush_cookie_actions()
    st.title("🔐 동행수첩 로그인")
    st.caption("등록된 아이디와 비밀번호를 입력해야 출석부 화면이 열립니다. (형식·문자 제약 없음)")

    expected_user = st.secrets.get("APP_USERNAME", "")
    expected_pass = st.secrets.get("APP_PASSWORD", "")

    if not expected_user or not expected_pass:
        st.warning(
            "Streamlit Cloud **Settings → Secrets**에 `APP_USERNAME`과 `APP_PASSWORD`를 먼저 설정해 주세요."
        )
        st.code(
            'APP_USERNAME = "원하는아이디"\nAPP_PASSWORD = "원하는비밀번호"\nAPP_AUTH_SALT = "임의의비밀문구"',
            language="toml",
        )
        st.stop()

    if not st.session_state.get("_logged_out"):
        if _verify_auth_token(_read_auth_cookie(), str(expected_user), str(expected_pass)):
            st.session_state["logged_in"] = True
            st.rerun()

    _, center_col, _ = st.columns([1, 2, 1])
    with center_col:
        with st.form(key="login_form"):
            input_id = st.text_input("아이디", placeholder="아이디 입력")
            input_pw = st.text_input("비밀번호", type="password", placeholder="비밀번호 입력")
            remember_device = st.checkbox(f"이 기기에서 로그인 유지 ({AUTH_DAYS}일)", value=True)
            login_submitted = st.form_submit_button("🔓 로그인")

            if login_submitted:
                if _exact_match(input_id, expected_user) and _exact_match(input_pw, expected_pass):
                    st.session_state["logged_in"] = True
                    st.session_state.pop("_logged_out", None)
                    if remember_device:
                        st.session_state["_cookie_set"] = _make_auth_token(
                            str(expected_user), str(expected_pass)
                        )
                    else:
                        st.session_state["_cookie_clear"] = True
                    st.rerun()
                else:
                    st.error("아이디 또는 비밀번호가 일치하지 않습니다.")

    st.stop()


