def normalize_mmdd(raw_val: str) -> str | None:
    if not raw_val:
        return None
    cleaned = (
        str(raw_val)
        .strip()
        .replace("년", "-")
        .replace("월", "-")
        .replace("일", "")
        .replace("/", "-")
        .replace(".", "-")
    )
    parts = [p.strip() for p in cleaned.split("-") if p.strip()]
    if len(parts) >= 2 and parts[-2].isdigit() and parts[-1].isdigit():
        m = int(parts[-2])
        d = int(parts[-1])
        if 1 <= m <= 12 and 1 <= d <= 31:
            return f"{m:02d}-{d:02d}"
    return None


def parse_salvation_input(raw: str) -> tuple[str | None, int | None]:
    """'1994-12-11' · '1994.12.11' · '1994년 12월 11일' · '19941211' · '12-11' -> ('12-11', 1994|None)"""
    text = str(raw or "").strip()
    if not text:
        return None, None
    year = None
    compact = re.fullmatch(r"(\d{4})(\d{2})(\d{2})", text)
    if compact:
        year, m, d = int(compact[1]), int(compact[2]), int(compact[3])
    else:
        nums = re.findall(r"\d+", text)
        if len(nums) == 3 and len(nums[0]) == 4:
            year, m, d = int(nums[0]), int(nums[1]), int(nums[2])
        elif len(nums) == 2:
            m, d = int(nums[0]), int(nums[1])
        else:
            return None, None
    if year is not None and not (1900 <= year <= datetime.datetime.now(KST).year):
        return None, None
    try:
        datetime.date(year or 2000, m, d)  # 연도가 없으면 윤년(2000) 기준이라 2/29도 허용
    except ValueError:
        return None, None
    return f"{m:02d}-{d:02d}", year


def split_memo(memo: str | None) -> tuple[str, str]:
    """DB memo 칸 -> (연도, 메모 글). 저장 형식은 '1994|상품 전달'.
    예전 형식('1994' 또는 연도가 섞인 글)도 읽을 수 있습니다."""
    raw = str(memo or "").strip()
    if "|" in raw:
        head, _, text = raw.partition("|")
        head = head.strip()
        year = head if re.fullmatch(r"(?:19|20)\d{2}", head) else ""
        return year, text.strip()
    found = re.search(r"(?:19|20)\d{2}", raw)
    if not found:
        return "", raw
    rest = (raw[: found.start()] + raw[found.end():]).strip(" ,/·-")
    return found.group(0), rest


def join_memo(year, text: str) -> str:
    year_txt = str(year) if year else ""
    text = (text or "").strip()
    return f"{year_txt}|{text}" if text else year_txt


