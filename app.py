def parse_names(text: str | None) -> list[str]:
    """쉼표/줄바꿈으로 구분된 이름을 중복 없이 순서대로 반환."""
    raw = str(text or "").replace("\n", ",").replace("，", ",")
    names: list[str] = []
    for part in raw.split(","):
        n = part.strip()
        if n and n not in names:
            names.append(n)
    return names


def current_year() -> int:
    return datetime.datetime.now(KST).year


def calc_age(birth_year) -> int | None:
    if not birth_year:
        return None
    try:
        year = int(birth_year)
    except (TypeError, ValueError):
        return None
    age = current_year() - year
    if AGE_STYLE == "korean":
        age += 1
    return age if age >= 0 else None


def parse_name_year_entries(text: str | None) -> tuple[list[tuple[str, int | None]], list[str]]:
    """'홍길동 1985, 김철수' 형태를 (이름, 출생년도|None) 목록으로 변환. (유효 목록, 잘못된 항목)"""
    raw = str(text or "").replace("\n", ",").replace("，", ",")
    entries: list[tuple[str, int | None]] = []
    invalid: list[str] = []
    seen: set[str] = set()
    max_year = current_year()
    for token in raw.split(","):
        token = token.strip()
        if not token:
            continue
        parts = token.split()
        year = None
        name = token
        if parts[-1].isdecimal():
            last = parts[-1]
            if len(parts) < 2 or len(last) != 4 or not (1900 <= int(last) <= max_year):
                invalid.append(token)
                continue
            year = int(last)
            name = " ".join(parts[:-1])
        if name in seen:
            continue
        seen.add(name)
        entries.append((name, year))
